class Libro:
    def __init__(self, id_libro, isbn, titulo, autor, categoria, anio, stock_total, stock_disponible):
        self.id_libro = id_libro
        self.isbn = isbn
        self.titulo = titulo
        self.autor = autor
        self.categoria = categoria
        self.anio = anio
        self.stock_total = stock_total
        self.stock_disponible = stock_disponible